/**
 * Read-only Snowflake access for the Monday job, through the Snowflake SQL API with
 * key-pair (JWT) auth. Server-only. Credentials come from the deployment's environment:
 *
 *   SNOWFLAKE_ACCOUNT      account identifier, e.g. ORGNAME-ACCOUNTNAME
 *   SNOWFLAKE_USER         a dedicated read-only service user
 *   SNOWFLAKE_PRIVATE_KEY  that user's PKCS#8 private key (PEM; "\n" escapes allowed)
 *   SNOWFLAKE_ROLE         a role with read on the semantic view only
 *   SNOWFLAKE_WAREHOUSE    the warehouse to run the query on
 *
 * Nothing here logs, returns or reports a credential.
 */
import { createHash, createPrivateKey, createPublicKey, sign } from "node:crypto";
import type { RawRow, SnowflakeRead } from "./monday-import";

const VARS = ["SNOWFLAKE_ACCOUNT", "SNOWFLAKE_USER", "SNOWFLAKE_PRIVATE_KEY", "SNOWFLAKE_ROLE", "SNOWFLAKE_WAREHOUSE"] as const;

export function snowflakeConfigured(): { ok: boolean; missing: string[] } {
  const missing = VARS.filter((v) => !process.env[v]?.trim());
  return { ok: missing.length === 0, missing };
}

const b64url = (b: Buffer | string) => Buffer.from(b).toString("base64url");

function jwt() {
  // The JWT names the account without any region/cloud suffix ("xy12345.us-east-2" → "XY12345").
  const account = process.env.SNOWFLAKE_ACCOUNT!.trim().toUpperCase().split(".")[0]!;
  const user = process.env.SNOWFLAKE_USER!.trim().toUpperCase();
  const key = createPrivateKey({
    key: process.env.SNOWFLAKE_PRIVATE_KEY!.replace(/\\n/g, "\n"),
    passphrase: process.env.SNOWFLAKE_PRIVATE_KEY_PASSPHRASE || undefined,
  });
  const der = createPublicKey(key).export({ type: "spki", format: "der" });
  const fingerprint = `SHA256:${createHash("sha256").update(der).digest("base64")}`;
  const now = Math.floor(Date.now() / 1000);
  const head = b64url(JSON.stringify({ alg: "RS256", typ: "JWT" }));
  const body = b64url(JSON.stringify({ iss: `${account}.${user}.${fingerprint}`, sub: `${account}.${user}`, iat: now, exp: now + 300 }));
  const sig = sign("RSA-SHA256", Buffer.from(`${head}.${body}`), key);
  return `${head}.${body}.${b64url(sig)}`;
}

type ApiResult = {
  statementHandle: string;
  data?: (string | null)[][];
  resultSetMetaData?: { rowType: { name: string }[]; partitionInfo?: unknown[] };
  message?: string;
  code?: string;
};

async function call(path: string, init: RequestInit): Promise<{ status: number; body: ApiResult }> {
  const host = `${process.env.SNOWFLAKE_ACCOUNT!.trim().toLowerCase()}.snowflakecomputing.com`;
  const res = await fetch(`https://${host}${path}`, {
    ...init,
    headers: {
      Authorization: `Bearer ${jwt()}`,
      "X-Snowflake-Authorization-Token-Type": "KEYPAIR_JWT",
      "Content-Type": "application/json",
      Accept: "application/json",
      "User-Agent": "waterman-battle-bot-league/1.0",
    },
    signal: AbortSignal.timeout(90_000),
  });
  const body = (await res.json().catch(() => ({}))) as ApiResult;
  return { status: res.status, body };
}

/** Run one read-only statement and return its rows as objects plus the query ID. */
async function query(statement: string): Promise<{ rows: Record<string, string | null>[]; queryId: string }> {
  const cfg = snowflakeConfigured();
  if (!cfg.ok) throw new Error(`Snowflake is not configured for the site (missing ${cfg.missing.join(", ")}).`);
  let { status, body } = await call("/api/v2/statements", {
    method: "POST",
    body: JSON.stringify({
      statement,
      timeout: 80,
      role: process.env.SNOWFLAKE_ROLE!.trim(),
      warehouse: process.env.SNOWFLAKE_WAREHOUSE!.trim(),
      parameters: { QUERY_TAG: "battle-bot-league-monday" },
    }),
  });
  // 202: still running. Poll the same statement; never resubmit.
  for (let i = 0; status === 202 && i < 20; i++) {
    await new Promise((r) => setTimeout(r, 2000));
    ({ status, body } = await call(`/api/v2/statements/${encodeURIComponent(body.statementHandle)}`, { method: "GET" }));
  }
  if (status === 401 || status === 403) throw new Error(`Snowflake refused the site's credentials (HTTP ${status}).`);
  if (status !== 200) throw new Error(`Snowflake query failed (HTTP ${status}${body.code ? `, code ${body.code}` : ""}${body.statementHandle ? `, query ${body.statementHandle}` : ""}).`);
  if ((body.resultSetMetaData?.partitionInfo?.length ?? 1) > 1) throw new Error(`Snowflake returned a multi-part result; expected one small table (query ${body.statementHandle}).`);
  const cols = body.resultSetMetaData?.rowType.map((c) => c.name.toLowerCase()) ?? [];
  const rows = (body.data ?? []).map((r) => Object.fromEntries(cols.map((c, i) => [c, r[i] ?? null])));
  return { rows, queryId: body.statementHandle };
}

/** Dates are generated by the job from the approved calendar; reject anything else before it reaches SQL. */
function isoDate(d: string) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) throw new Error(`Bad date ${d}`);
  return d;
}

/** The week's raw sums per store (Sunday–Saturday, Central business dates), plus how far the source has loaded. */
export function weekStatement(start: string, end: string) {
  const s = isoDate(start);
  const e = isoDate(end);
  const view = "DATA_PLATFORM_DB_PROD.AI.CUSTOMER_TRAFFIC_AD_SPEND";
  const franchises = "franchise.franchise IN ('WATERMAN', 'MCDONALD')";
  return `SELECT store, store_number, franchise, new_up_sales, new_ups, walkouts, demos_seen, demos_sold, demo_sales, arch_supports_sold, arch_supports_returned,
(SELECT MAX(date) FROM SEMANTIC_VIEW(${view} DIMENSIONS dim_date.date METRICS traffic_event_summary_dt.new_ups WHERE ${franchises} AND dim_date.date >= DATE '${s}')) AS latest_date
FROM SEMANTIC_VIEW(${view}
DIMENSIONS stores.store, stores.store_number, franchise.franchise
METRICS traffic_event_summary_dt.new_up_sales, traffic_event_summary_dt.new_ups, traffic_event_summary_dt.walkouts, traffic_event_summary_dt.demos_seen, traffic_event_summary_dt.demos_sold, traffic_event_summary_dt.demo_sales, traffic_event_summary_dt.arch_supports_sold, traffic_event_summary_dt.arch_supports_returned
WHERE ${franchises} AND dim_date.date BETWEEN DATE '${s}' AND DATE '${e}')
ORDER BY store_number`;
}

/** The SQL API sends DATE values as days since 1970-01-01. */
export function sqlDate(v: string | null | undefined): string | null {
  if (!v) return null;
  if (/^\d{4}-\d{2}-\d{2}/.test(v)) return v.slice(0, 10);
  if (/^-?\d+$/.test(v)) return new Date(Number(v) * 86_400_000).toISOString().slice(0, 10);
  return null;
}

export async function fetchWeek(start: string, end: string): Promise<SnowflakeRead> {
  const { rows, queryId } = await query(weekStatement(start, end));
  const latest = rows.map((r) => sqlDate(r.latest_date)).filter((d): d is string => Boolean(d)).sort().at(-1) ?? null;
  return {
    rows: rows.map(({ latest_date: _latest, ...r }) => r as unknown as RawRow),
    latestDate: latest,
    queryIds: [queryId],
  };
}
